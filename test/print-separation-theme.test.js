'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'portal','index.html'),'utf8');
const start=html.indexOf('popup.document.write(');
const title=html.indexOf('<title>Lista de Separação</title>',start);
const end=html.indexOf('</style>',title);
assert.ok(start>0&&title>start&&end>title);
const style=html.slice(title,end);
const print=style.slice(style.indexOf('@media print{'));
assert.match(style,/h1\{[^}]*color:#14213d/);
assert.match(style,/#fca311/);
assert.match(style,/th\{background:#14213d;color:#fff\}/);
assert.match(print,/background:#fff!important/);
assert.match(print,/border:1px solid #000!important;background:#fff!important/);
assert.match(print,/grayscale\(100%\)/);
assert.doesNotMatch(print,/#52a388|#eef6f3|#cbe1da/);
assert.match(html,/mlsh-design-system\.css\?v=20261119-coolpalette-1/);
const css=fs.readFileSync(path.join(root,'portal','mlsh-design-system.css'),'utf8');
assert.match(css,/--panel-2:#F2F5FA/);
assert.match(css,/--table-hover:#F3F6FC/);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(x=>x[1]).filter(x=>x.trim());
for(const script of scripts)new Function(script);
console.log('PASS: preview navy/orange, print strictly black/white and grayscale, light workspace palette and inline JS syntax');
