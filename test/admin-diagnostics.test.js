'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const html=fs.readFileSync(path.join(root,'admin/index.html'),'utf8');
const appjs=fs.readFileSync(path.join(root,'admin/js/app.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'admin/js/diagnostics.js'),'utf8');
const start=server.indexOf('app.get("/api/admin/diagnostics"');
const end=server.indexOf('app.get("/api/admin/test"',start);
assert.ok(start>0&&end>start,'admin endpoint missing');
let registered, middleware;
const app={get(path,auth,handler){assert.equal(path,'/api/admin/diagnostics');registered=handler;middleware=auth}};
const verificarAdmin=()=>{};
const seen=[];
const supabase={from(table){seen.push(table);return {select(_fields,_opts){return Promise.resolve({count:({companies:5,mercadolivre_accounts:4,bling_connections:2,devices:9})[table]??0,error:null})}}}};
vm.runInNewContext(server.slice(start,end),{app,verificarAdmin,supabase,Date,Promise});
assert.equal(middleware,verificarAdmin,'endpoint must require admin auth');
assert.equal(typeof registered,'function');
(async()=>{
 let payload,cache;
 await registered({}, {set(k,v){if(k==='Cache-Control')cache=v},json(data){payload=data}});
 assert.equal(cache,'no-store');
 assert.equal(payload.ok,true);
 assert.equal(payload.integrations.mercadolivre.registeredAccounts,4);
 assert.equal(payload.integrations.bling.registeredAccounts,2);
 assert.equal(payload.integrations.mercadolivre.tokenValidated,false);
 assert.equal(payload.integrations.shopee.status,'not_monitored');
 assert.equal(payload.database.status,'ok');
 assert.deepEqual(seen.sort(),['bling_connections','companies','devices','mercadolivre_accounts'].sort());
 assert.ok(!JSON.stringify(payload).match(/secret|access_token|refresh_token|license_key/i));
 assert.match(html,/data-page="diagnostics"/);
 assert.match(html,/js\/diagnostics\.js/);
 assert.match(appjs,/adminDiagnosticsPage\.render\(\)/);
 assert.match(ui,/api\/admin\/diagnostics/);
 assert.doesNotMatch(ui,/clipboard|Copiar diagnóstico|copyReport|download/);
 console.log('PASS: admin-only endpoint, no secrets, card data and no copy UI');
})().catch(e=>{console.error(e);process.exitCode=1});
