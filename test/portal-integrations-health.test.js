'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const portal=fs.readFileSync(path.join(root,'portal/index.html'),'utf8');
const code=fs.readFileSync(path.join(root,'portal/integrations-health.js'),'utf8');
assert.match(portal,/integrations-health\.js/);
assert.match(portal,/mlshIntegrationHealth\?\.markup\(\)/);
assert.match(portal,/mlshIntegrationHealth\?\.init/);
assert.match(portal,/mlsh-design-system\.css/);
const w={};
vm.runInNewContext(code,{window:w,document:{},Date,Promise});
const markup=w.mlshIntegrationHealth.markup();
assert.match(markup,/Saúde das integrações/);
assert.match(markup,/Verificar agora/);
assert.doesNotMatch(markup,/Copiar diagnóstico|clipboard|Exportar/);
let called=[],onClick;
const nodes={};
const node=id=>nodes[id]||(nodes[id]={textContent:'',dataset:{},disabled:false,addEventListener:(name,fn)=>{if(id==='#mlshIntegrationsRefresh')onClick=fn;}});
const fake={isConnected:true,querySelector:node};
const doc={getElementById:id=>id==='mlshIntegrationsHealth'?fake:null};
const context={window:{},document:doc,Date,Promise};
vm.runInNewContext(code,context);
const api=async endpoint=>{
 called.push(endpoint);
 if(endpoint==='/api/portal/me')return {user:{id:1}};
 if(endpoint==='/api/portal/dashboard')return {ok:true,ml_connected:true};
 if(endpoint==='/api/portal/bling/connections')return {connections:[{id:1},{id:2}]};
 throw Error('unexpected endpoint '+endpoint);
};
context.window.mlshIntegrationHealth.init({api,dashboard:{ml_connected:false}});
(async()=>{
 await onClick();
 assert.deepEqual(called.sort(),['/api/portal/me','/api/portal/dashboard','/api/portal/bling/connections'].sort());
 assert.equal(node('[data-hl="api"]').textContent,'Respondendo');
 assert.equal(node('[data-hl="ml"]').textContent,'Conta vinculada');
 assert.equal(node('[data-hl="bling"]').textContent,'2 conexão(ões) cadastrada(s)');
 assert.equal(node('[data-hl="shopee"]').textContent,'');
 assert.equal(node('#mlshIntegrationsRefresh').disabled,false);
 console.log('PASS: portal settings health uses real endpoints, no copy, no misleading connection claim');
})().catch(e=>{console.error(e);process.exitCode=1});
